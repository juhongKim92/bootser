/**
 * 카드에 찍을 수 있는 꼴로 바꾼다.
 * NFD 로 분해해 결합 발음기호를 떼면 Å·ô·ç 가 A·O·C 가 된다 — 이것이
 * `countries.json` 의 204개 이름을 31자 안으로 밀어넣는 유일한 수단이다.
 * 아포스트로피(Côte d'Ivoire 는 정규화 뒤에도 남는다)는 글자를 늘리기보다 지운다.
 */
export const normalize = (s) => s
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/['\u2019.]/g, '')
    .toUpperCase();

/** 원화가 성립하는지 — 크기, 알 수 없는 문자, 그리고 글자가 실제로 그려졌는지. */
export function validate(glyphs = GLYPHS) {
    const bad = [];
    for (const [ch, rows] of Object.entries(glyphs)) {
        if (rows.length !== FH) bad.push(`'${ch}' 의 행이 ${rows.length}개다 (${FH}이어야 한다)`);
        rows.forEach((row, y) => {
            if (row.length !== FW) bad.push(`'${ch}' ${y}행 길이가 ${row.length}이다 (${FW}이어야 한다)`);
            for (const c of row) if (c !== '#' && c !== '.') bad.push(`'${ch}' ${y}행에 알 수 없는 문자 '${c}'`);
        });
        /* 빈 글자는 공백뿐이어야 한다. 찍다 만 글자가 조용히 공백으로 보이는 것을 막는다 */
        const ink = rows.join('').includes('#');
        if (!ink && ch !== ' ') bad.push(`'${ch}' 가 비어 있다 — 찍다 말았다`);
        if (ink && ch === ' ') bad.push(`공백에 잉크가 있다`);
    }
    /* A-Z 가 다 있어야 한다. 국가 코드는 전부 A-Z 라 하나만 빠져도 카드가 깨진다 */
    for (let i = 0; i < 26; i++) {
        const ch = String.fromCharCode(65 + i);
        if (!(ch in glyphs)) bad.push(`'${ch}' 가 없다`);
    }
    /* 서로 다른 글자가 똑같이 생기면 읽는 사람은 구별하지 못한다.
       O 와 Q, C 와 G 처럼 닮은 짝을 손으로 찍다 보면 실제로 벌어진다. */
    const seen = new Map();
    for (const [ch, rows] of Object.entries(glyphs)) {
        if (ch === ' ') continue;
        const key = rows.join('|');
        if (seen.has(key)) bad.push(`'${seen.get(key)}' 와 '${ch}' 가 똑같이 생겼다`);
        seen.set(key, ch);
    }
    return [...new Set(bad)];
}
